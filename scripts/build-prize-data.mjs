function slug(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '.').replace(/^\.|\.$/g, '')
}

const rows = RAW.split('\n').filter(Boolean).map((line, i) => {
  const [name, cnic, mobile, invoice, business, prize, amount] = line.split('|')
  const id = `PW-${String(i + 1).padStart(4, '0')}`
  const cnicDigits = cnic.trim().replace(/\D/g, '')
  const mobileDigits = mobile.trim().replace(/\D/g, '')
  return {
    id,
    name: name.trim(),
    cnic: cnicDigits,
    mobile: mobileDigits,
    suffixKeys: `${cnicDigits.slice(-4)} ${mobileDigits.slice(-4)}`,
    invoiceNumber: invoice.trim(),
    businessName: business.trim(),
    prize: prize.trim(),
    prizeAmount: Number(amount).toLocaleString('en-US'),
    username: slug(name),
  }
})

